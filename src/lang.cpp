// The platform's own text in the game's language (platform 2.9.0), and the game's language for the mods (API 10).
//
// The language: the string tables' manager (a pointer at game+0x3662990, FH2_GAME_STRING_TABLES) keeps the text
// language's code at +0x30, an MSVC std::string ("EN", "CHT"...: short, so its characters are in place, with the
// length at +0x10 and the capacity, 15, at +0x18). It's set once the game has read its language option; Extra
// Options and FH2 ANNA read it there too. Before that, and in Czech and Hungarian (the game's text there is
// English), the text is English.
//
// The pages are written as they're opened, by then in the game's language; the restart prompt and the title
// screen's lists ask for their text as they're shown. Every translation only uses characters the game's font for
// its language has (media\ui\Fonts.zip: Anthem for Latin text, with Verdana for Russian, and for Japanese, Korean
// and Chinese a font with only the characters the game's own text uses): check new text against them, or it shows
// as boxes. Names the player sees in English stay so: MODS, GET MODS, FH2 Mod Platform, Extra Options, FH2MP.
