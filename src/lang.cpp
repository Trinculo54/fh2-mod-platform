const Text* find_text(const char* english) {
    for (const Text& t : kTexts)
        if (!std::strcmp(t.en, english)) return &t;
    return nullptr;
}

// The game's text language: an index into kCodes, or -1 for English (and before the game has one).
int language() {
    char code[8];
    if (!game_language(code, sizeof code)) return -1;
    for (int i = 0; i < kLangs; ++i)
        if (!std::strcmp(code, kCodes[i])) return i;
    return -1;
}

std::string narrow_utf8(const wchar_t* w) {
    const int n = WideCharToMultiByte(CP_UTF8, 0, w, -1, nullptr, 0, nullptr, nullptr);
    std::string s(n > 0 ? n - 1 : 0, '\0');
    if (n > 1) WideCharToMultiByte(CP_UTF8, 0, w, -1, s.data(), n, nullptr, nullptr);
    return s;
}

std::wstring widen_utf8(const char* s) {
    const int n = MultiByteToWideChar(CP_UTF8, 0, s, -1, nullptr, 0);
    std::wstring w(n > 0 ? n - 1 : 0, L'\0');
    if (n > 1) MultiByteToWideChar(CP_UTF8, 0, s, -1, w.data(), n);
    return w;
}

