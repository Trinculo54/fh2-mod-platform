int game_language(char* code, size_t size) {
    if (!code || size < 4) return 0;
    code[0] = '\0';
    // Until the game is found, find_game() searches memory: once a second at most from here
    static std::atomic<const uint8_t*> known{nullptr};
    static std::atomic<uint64_t> searched{0};
    const uint8_t* game = known.load();
    if (!game) {
        const uint64_t now = GetTickCount64();
        if (now - searched.load() < 1000) return 0;
        searched = now;
        known    = game = static_cast<const uint8_t*>(find_game());
    }
    const uint8_t* manager = nullptr;
    uint8_t s[0x20];
    if (!game || !safe_copy(&manager, game + RVA_STRING_TABLES, sizeof manager) || !manager ||
        !safe_copy(s, manager + 0x30, sizeof s))
        return 0;
    uint64_t length = 0, capacity = 0;
    std::memcpy(&length, s + 0x10, sizeof length);
    std::memcpy(&capacity, s + 0x18, sizeof capacity);
    if (capacity != 15 || length < 2 || length > 3 || length >= size || s[length]) return 0;
    for (uint64_t i = 0; i < length; ++i) {
        if (!std::isalpha(s[i])) return 0;
        code[i] = static_cast<char>(std::toupper(s[i]));   // the zips are "br", "nl", "cz"...: the codes in capitals
    }
    code[length] = '\0';
    return 1;
}

std::string tr(const char* english) {
    if (!english) return "";
    const int l = language();
    const Text* t = l < 0 ? nullptr : find_text(english);
    return t ? t->t[l] : english;
}

std::string trf(const char* english, std::initializer_list<std::string> args) {
    std::string s = tr(english);
    int n = 0;
    for (const std::string& a : args) {
        const std::string mark = "{" + std::to_string(n++) + "}";
        if (const std::size_t at = s.find(mark); at != std::string::npos) s.replace(at, mark.size(), a);
    }
    return s;
}

const wchar_t* tr_w(const wchar_t* english) {
    const int l = english ? language() : -1;
    if (l < 0) return english;
    static std::mutex mu;
    static std::map<std::pair<int, const wchar_t*>, std::wstring> made;   // never freed: shown text points into it
    std::scoped_lock lk{mu};
    auto it = made.find({l, english});
    if (it == made.end()) {
        const Text* t = find_text(narrow_utf8(english).c_str());
        it            = made.emplace(std::make_pair(l, english), t ? widen_utf8(t->t[l]) : std::wstring(english)).first;
    }
    return it->second.c_str();
}

